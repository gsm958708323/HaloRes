using System.IO;
using System.Text;
using GameUI.Components;
using UnityEditor;
using UnityEngine;

namespace GameUI.Editor
{
    public static class UIBindingEmitter
    {
        [MenuItem("GameUI/Generate Binding Code")]
        public static void GenerateSelected()
        {
            var prefab = Selection.activeObject as GameObject;
            if (prefab == null) { Debug.LogWarning("Select a UI prefab first."); return; }
            var binding = prefab.GetComponent<UIBindingData>();
            if (binding == null) { Debug.LogWarning("Selected prefab has no UIBindingData."); return; }
            var path = AssetDatabase.GetAssetPath(prefab);
            var directory = Path.GetDirectoryName(path).Replace('\\', '/');
            var name = Path.GetFileNameWithoutExtension(path);
            var output = Path.Combine(directory, name + ".Binding.g.cs").Replace('\\', '/');
            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated by GameUIBindingEmitter />");
            builder.AppendLine("namespace GameUI.Generated { public static class " + name + "Binding {");
            builder.AppendLine("public const uint LayoutHash = 0x" + binding.layoutHash.ToString("X8") + ";");
            for (var i = 0; i < binding.entries.Count; i++)
                builder.AppendLine("public const int " + Sanitize(binding.entries[i].name, i) + " = " + i + ";");
            builder.AppendLine("} }");
            File.WriteAllText(output, builder.ToString(), Encoding.UTF8);
            AssetDatabase.ImportAsset(output);
            Debug.Log("Generated " + output);
        }

        private static string Sanitize(string value, int fallback)
        {
            if (string.IsNullOrEmpty(value)) return "Entry" + fallback;
            var builder = new StringBuilder(value.Length);
            for (var i = 0; i < value.Length; i++) builder.Append(char.IsLetterOrDigit(value[i]) ? value[i] : '_');
            if (char.IsDigit(builder[0])) builder.Insert(0, '_');
            return builder.ToString();
        }
    }
}
