using System;
using System.IO;
using System.Text;
using GameUI.Components;
using UnityEditor;
using UnityEngine;

namespace GameUI.Editor
{
    public static class UIBindingEmitter
    {
        [MenuItem("GameUI/Generate Binding Code")]
        public static void GenerateSelected()
        {
            var root = Selection.activeObject as GameObject;
            if (root == null) throw new InvalidOperationException("Select a UI prefab.");
            Generate(root.GetComponent<UIBindingData>());
        }

        public static string Generate(UIBindingData data, string className = null, string namespaceName = null, string directory = null)
        {
            if (data == null) throw new ArgumentNullException(nameof(data));
            var path = AssetDatabase.GetAssetPath(data.gameObject);
            directory = directory ?? Path.GetDirectoryName(path)?.Replace('\\', '/');
            if (string.IsNullOrEmpty(directory)) throw new InvalidOperationException("Save the prefab before generating bindings.");
            if (className == null && !string.IsNullOrEmpty(data.logicType))
            {
                var split = data.logicType.LastIndexOf('.');
                className = split < 0 ? data.logicType : data.logicType.Substring(split + 1);
                namespaceName = split < 0 ? "" : data.logicType.Substring(0, split);
            }
            className = className ?? UIRegistryEmitter.Identifier(data.name);
            namespaceName = namespaceName ?? "GameUI.Views";
            var hash = ComputeLayoutHash(data);
            data.layoutHash = hash;
            EditorUtility.SetDirty(data);
            var b = new StringBuilder("// <auto-generated />\n" + (namespaceName.Length == 0 ? "" : "namespace " + namespaceName + "\n{\n"));
            b.Append("    public sealed partial class ").Append(className).Append("\n    {\n        public const uint BindingLayoutHash = 0x").Append(hash.ToString("X8")).Append(";\n");
            for (var i=0; i<data.entries.Count; i++)
            {
                var e=data.entries[i];
                if (e == null || e.component == null) throw new InvalidOperationException("Empty binding entry " + i);
                b.Append("        private ").Append(UIRegistryEmitter.TypeName(e.component.GetType())).Append(" _").Append(UIRegistryEmitter.Identifier(e.name)).Append(";\n");
            }
            for (var i=0; i<data.nodes.Count; i++)
            {
                var n=data.nodes[i];
                if (n == null || n.data == null) throw new InvalidOperationException("Empty binding node " + i);
                var panel=string.Equals(n.kind,"Panel",StringComparison.OrdinalIgnoreCase);
                if (panel && string.IsNullOrEmpty(n.typeName)) throw new InvalidOperationException("Panel type is required.");
                b.Append("        private global::").Append(panel ? n.typeName : "GameUI.Components.UIBindingData")
                    .Append(" _").Append(UIRegistryEmitter.Identifier(n.data.name)).Append(";\n");
            }
            b.Append("        protected override void BindControls(global::GameUI.Components.UIBindingData data)\n        {\n            data.CheckLayout(BindingLayoutHash);\n");
            for (var i=0; i<data.entries.Count; i++)
            {
                var e=data.entries[i];
                b.Append("            _").Append(UIRegistryEmitter.Identifier(e.name)).Append(" = data.Get<").Append(UIRegistryEmitter.TypeName(e.component.GetType())).Append(">(").Append(i).Append(");\n");
            }
            for (var i=0; i<data.nodes.Count; i++)
            {
                var n=data.nodes[i];
                if (n == null || n.data == null) continue;
                if (string.Equals(n.kind, "Panel", StringComparison.OrdinalIgnoreCase))
                    b.Append("            _").Append(UIRegistryEmitter.Identifier(n.data.name)).Append(" = AddPanel(new global::").Append(n.typeName).Append("(), data.Node(").Append(i).Append("));\n");
                else b.Append("            _").Append(UIRegistryEmitter.Identifier(n.data.name)).Append(" = data.Node(").Append(i).Append(");\n");
            }
            b.Append("        }\n    }\n");
            if (namespaceName.Length > 0) b.Append("}\n");
            var output=directory + "/" + className + ".Binding.g.cs";
            UIRegistryEmitter.WriteIfChanged(output, b.ToString());
            return output;
        }

        public static uint ComputeLayoutHash(UIBindingData data)
        {
            uint hash=2166136261;
            foreach (var e in data.entries)
            {
                if (e == null || e.component == null) throw new InvalidOperationException("Empty binding entry.");
                Hash(ref hash, e.name); Hash(ref hash, e.component.GetType().FullName);
                Hash(ref hash, RelativePath(data.transform,e.component.transform));
            }
            foreach (var n in data.nodes)
            {
                if (n == null) throw new InvalidOperationException("Null binding node.");
                Hash(ref hash,n.kind); Hash(ref hash,n.typeName);
                Hash(ref hash,n.data == null ? "<null>" : n.data.layoutHash.ToString("X8"));
            }
            return hash == 0 ? 1u : hash;
        }
        private static void Hash(ref uint hash,string value)
        {
            foreach (var ch in value ?? "") { hash ^= ch; hash *= 16777619; }
            hash ^= 255; hash *= 16777619;
        }
        private static string RelativePath(Transform root,Transform item)
        {
            if (item == root) return "";
            var result=item.name;
            while (item.parent != root && item.parent != null) { item=item.parent; result=item.name + "/" + result; }
            item=item.parent;
            if (item != root) throw new InvalidOperationException("Binding must refer to the prefab tree.");
            return result;
        }
    }
}
