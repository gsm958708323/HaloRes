using System;
using System.IO;
using System.Linq;
using System.Text;
using GameUI.Kernel;
using GameUI.Runtime;
using UnityEditor;
using UnityEditor.Callbacks;
using UnityEditor.Compilation;

namespace GameUI.Editor
{
    public static class UIRegistryEmitter
    {
        [MenuItem("GameUI/Generate UIView Registry")]
        public static void Generate()
        {
            foreach (var group in TypeCache.GetTypesWithAttribute<UIViewAttribute>()
                .Where(t => typeof(UIView).IsAssignableFrom(t) && !t.IsAbstract && !t.ContainsGenericParameters)
                .GroupBy(t => t.Assembly.GetName().Name))
            {
                var assembly = CompilationPipeline.GetAssemblies().FirstOrDefault(a => a.name == group.Key);
                var script = assembly?.sourceFiles.FirstOrDefault(p => p.Replace('\\', '/').StartsWith("Assets/") && !p.EndsWith(".g.cs"));
                if (script == null) continue;
                var folder = FindAssemblyFolder(script);
                var className = Identifier(group.Key) + "Registry";
                var output = folder + "/Generated/" + className + ".g.cs";
                var b = new StringBuilder("// <auto-generated />\nusing GameUI.Kernel;\nnamespace GameUI.Generated\n{\n");
                b.Append("    public static class ").Append(className).Append("\n    {\n        public static UIViewRegistry Create()\n        {\n            return new UIViewRegistry(new UIViewInfo[]\n            {\n");
                foreach (var type in group.OrderBy(t => t.FullName, StringComparer.Ordinal))
                {
                    var a = (UIViewAttribute)Attribute.GetCustomAttribute(type, typeof(UIViewAttribute));
                    var id = type.FullName.Replace('.', '/');
                    new UIViewInfo { Id=id, ViewType=type, Factory=()=>null, Mode=a.Mode, Layer=a.Layer }.Validate();
                    Type args = null, result = null;
                    for (var p = type.BaseType; p != null; p = p.BaseType)
                    {
                        if (!p.IsGenericType) continue;
                        if (p.GetGenericTypeDefinition() == typeof(UIView<,>)) { args=p.GetGenericArguments()[0]; result=p.GetGenericArguments()[1]; break; }
                        if (p.GetGenericTypeDefinition() == typeof(UIView<>)) args=p.GetGenericArguments()[0];
                    }
                    b.Append("                new UIViewInfo { Id=").Append(Literal(id)).Append(", ViewType=typeof(").Append(TypeName(type)).Append("), ");
                    if (args != null) b.Append("ArgsType=typeof(").Append(TypeName(args)).Append("), ");
                    if (result != null) b.Append("ResultType=typeof(").Append(TypeName(result)).Append("), ");
                    b.Append("Mode=UIMode.").Append(a.Mode).Append(", Layer=UILayer.").Append(a.Layer)
                        .Append(", CoversWorld=").Append(Bool(a.CoversWorld)).Append(", Context=").Append(Literal(a.Context))
                        .Append(", Visibility=UIOverlayVisibility.").Append(a.Visibility).Append(", ContextTag=").Append(Literal(a.ContextTag))
                        .Append(", BackBehavior=UIBackBehavior.").Append(a.Back).Append(", MaskStyle=UIMaskStyle.").Append(a.Mask)
                        .Append(", CloseOnMaskClick=").Append(Bool(a.CloseOnMaskClick)).Append(", KeepAlive=").Append(Bool(a.KeepAlive))
                        .Append(", InstancePolicy=UIInstancePolicy.").Append(a.Instance)
                        .Append(", PrefabPath=").Append(Literal(string.IsNullOrEmpty(a.PrefabPath) ? id : a.PrefabPath))
                        .Append(", Factory=()=>new ").Append(TypeName(type)).Append("() },\n");
                }
                b.Append("            });\n        }\n    }\n}\n");
                WriteIfChanged(output, b.ToString());
            }
        }

        [DidReloadScripts]
        private static void AfterCompilation() { EditorApplication.delayCall += Generate; }

        internal static string TypeName(Type type)
        {
            if (!type.IsGenericType) return "global::" + type.FullName.Replace('+', '.');
            var name = type.GetGenericTypeDefinition().FullName;
            name = name.Substring(0, name.IndexOf((char)96)).Replace('+', '.');
            return "global::" + name + "<" + string.Join(", ", type.GetGenericArguments().Select(TypeName)) + ">";
        }
        internal static string Literal(string value)
        {
            if (value == null) return "null";
            return "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n") + "\"";
        }
        internal static string Identifier(string value)
        {
            var b = new StringBuilder();
            foreach (var ch in value) b.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
            if (b.Length == 0 || char.IsDigit(b[0])) b.Insert(0, '_');
            return b.ToString();
        }
        internal static void WriteIfChanged(string path, string content)
        {
            content = content.Replace("\r\n", "\n");
            if (File.Exists(path) && File.ReadAllText(path).Replace("\r\n", "\n") == content) return;
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, content, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
        }
        private static string Bool(bool value) { return value ? "true" : "false"; }
        private static string FindAssemblyFolder(string path)
        {
            var directory = Path.GetDirectoryName(path).Replace('\\', '/');
            while (directory != "Assets" && !string.IsNullOrEmpty(directory))
            {
                if (Directory.GetFiles(directory, "*.asmdef").Length != 0) return directory;
                directory = Path.GetDirectoryName(directory)?.Replace('\\', '/');
            }
            return "Assets";
        }
    }
}
